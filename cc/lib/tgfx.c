void tg_init(char *buf) {
  tg_fb = buf;
  for (int i = 0; i < 23040; i++) buf[i] = 0;
  tg_noclip();
  VMODE = 1;
  FB_ADDR = (long)buf;
}

void tg_present(void) { FB_PRESENT = 0; }

void tg_noclip(void) { tg_cx0 = 0; tg_cy0 = 0; tg_cx1 = TRIT_W; tg_cy1 = TRIT_H; }

void tg_clip(int x, int y, int w, int h) {
  tg_cx0 = x < 0 ? 0 : x;
  tg_cy0 = y < 0 ? 0 : y;
  tg_cx1 = x + w > TRIT_W ? TRIT_W : x + w;
  tg_cy1 = y + h > TRIT_H ? TRIT_H : y + h;
}

static void tg_set(char *row, int x, int t) {
  int pw = POW3[x % 9];
  char *p = row + x / 9;
  int v = *p;
  *p = v + (t - ((v + 9841) / pw % 3 - 1)) * pw;
}

void tg_pixel(int x, int y, int t) {
  if (x < tg_cx0 || x >= tg_cx1 || y < tg_cy0 || y >= tg_cy1) return;
  tg_set(tg_fb + y * 64, x, t);
}

int tg_get(int x, int y) {
  if (x < 0 || x >= TRIT_W || y < 0 || y >= TRIT_H) return 0;
  return (tg_fb[y * 64 + x / 9] + 9841) / POW3[x % 9] % 3 - 1;
}

static void tg_prep(int pat) {
  if (pat < 2) return;
  tg_da = (pat - 2) / 3 - 1;
  tg_db = (pat - 2) % 3 - 1;
  tg_wev = 0; tg_wod = 0;
  for (int k = 0; k < 9; k++) {
    tg_wev += (k % 2 == 0 ? tg_da : tg_db) * POW3[k];
    tg_wod += (k % 2 == 0 ? tg_db : tg_da) * POW3[k];
  }
}

/* ligne y, pixels [x0,x1) déjà clippés ; tg_prep(pat) déjà appelé */
static void tg_span(int x0, int x1, int y, int pat) {
  char *row = tg_fb + y * 64;
  int x = x0, tx;
  if (pat < 2) {
    while (x < x1 && x % 9) { tg_set(row, x, pat); x++; }
    tx = x / 9;
    int w = pat * 9841;
    while (x + 9 <= x1) { row[tx] = w; tx++; x += 9; }
    while (x < x1) { tg_set(row, x, pat); x++; }
  } else {
    /* trame 50 % façon System 7 : colonnes alternées (x seul), stables sur toutes
       les lignes — donne des rayures verticales régulières. */
    while (x < x1 && x % 9) { tg_set(row, x, x % 2 == 0 ? tg_da : tg_db); x++; }
    tx = x / 9;
    while (x + 9 <= x1) { row[tx] = (tx % 2 == 0) ? tg_wev : tg_wod; tx++; x += 9; }
    while (x < x1) { tg_set(row, x, x % 2 == 0 ? tg_da : tg_db); x++; }
  }
}

void tg_fillrect(int x, int y, int w, int h, int pat) {
  int x1 = x + w, y1 = y + h;
  if (x < tg_cx0) x = tg_cx0;
  if (y < tg_cy0) y = tg_cy0;
  if (x1 > tg_cx1) x1 = tg_cx1;
  if (y1 > tg_cy1) y1 = tg_cy1;
  if (x >= x1 || y >= y1) return;
  tg_prep(pat);
  for (; y < y1; y++) tg_span(x, x1, y, pat);
}

void tg_hline(int x, int y, int w, int pat) { tg_fillrect(x, y, w, 1, pat); }
void tg_vline(int x, int y, int h, int pat) { tg_fillrect(x, y, 1, h, pat); }

void tg_rect(int x, int y, int w, int h, int pat) {
  tg_fillrect(x, y, w, 1, pat);
  tg_fillrect(x, y + h - 1, w, 1, pat);
  tg_fillrect(x, y + 1, 1, h - 2, pat);
  tg_fillrect(x + w - 1, y + 1, 1, h - 2, pat);
}

int tg_textw(const char *s) { int n = 0; while (*s++) n += 6; return n; }

void tg_text(int x, int y, const char *s, int t) {
  int c;
  while ((c = *s++) != 0) {
    if (c >= 32 && c < 127 && x + 6 > tg_cx0 && x < tg_cx1 && y + 8 > tg_cy0 && y < tg_cy1) {
      const short *g = TG_FONT + (c - 32) * 5;
      for (int col = 0; col < 5; col++) {
        int b = g[col];
        for (int r = 0; b; r++, b /= 2)
          if (b % 2) tg_pixel(x + col, y + r, t);
      }
    }
    x += 6;
  }
}

void tg_save(int tx, int y, int n, int h, char *dst) {
  for (int r = 0; r < h; r++)
    for (int i = 0; i < n; i++)
      if (y + r >= 0 && y + r < TRIT_H && tx + i >= 0 && tx + i < 64) dst[r * n + i] = tg_fb[(y + r) * 64 + tx + i];
}

void tg_restore(int tx, int y, int n, int h, const char *src) {
  for (int r = 0; r < h; r++)
    for (int i = 0; i < n; i++)
      if (y + r >= 0 && y + r < TRIT_H && tx + i >= 0 && tx + i < 64) tg_fb[(y + r) * 64 + tx + i] = src[r * n + i];
}
